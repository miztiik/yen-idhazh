import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import test from 'node:test';

const FRONTEND = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const CLI = join(FRONTEND, 'scripts/state-csv-guard.ts');

function repository(run) {
	const parent = resolve(FRONTEND, '../backend/var/checks/scope-tests');
	mkdirSync(parent, { recursive: true });
	const root = mkdtempSync(join(parent, 'state-csv-'));
	const git = (...args) => execFileSync('git', ['-C', root, '-c', 'user.name=Test',
		'-c', 'user.email=test@example.invalid', ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
	const write = (path, text = 'original\n') => {
		mkdirSync(dirname(join(root, path)), { recursive: true });
		writeFileSync(join(root, path), text);
	};
	const commit = () => {
		// This repository was generated by this test; its input size is fixed.
		git('add', '--all');
		git('commit', '--quiet', '-m', 'fixture');
		return git('rev-parse', 'HEAD');
	};
	const cli = (base, head, event = 'pull_request') => spawnSync(process.execPath, [CLI], {
		cwd: root, encoding: 'utf8', env: { ...process.env, BASE: base, HEAD: head, EVENT: event }
	});
	try {
		git('init', '--quiet');
		write('seed');
		write('outside.csv');
		write('state/legacy.csv');
		const base = commit();
		run({ root, git, write, commit, cli, base });
	} finally {
		rmSync(root, { recursive: true, force: true });
	}
}

function rejected(result, message) {
	assert.equal(result.error, undefined);
	assert.equal(result.signal, null);
	assert.equal(result.status, 1, result.stdout + result.stderr);
	assert.match(result.stderr, message);
	assert.equal(result.stdout, '');
}

function accepted(result, message = /passed for the supplied commit range; unchanged files were not checked/) {
	assert.equal(result.error, undefined);
	assert.equal(result.status, 0, result.stderr);
	assert.equal(result.stderr, '');
	assert.match(result.stdout, message);
}

for (const [name, change, path] of [
	['added', ({ write }) => write('state/new.csv'), 'state/new.csv'],
	['nested', ({ write }) => write('state/daily/new.csv'), 'state/daily/new.csv'],
	['modified', ({ write }) => write('state/legacy.csv', 'changed\n'), 'state/legacy.csv'],
	['renamed in', ({ git }) => git('mv', 'outside.csv', 'state/in.csv'), 'state/in.csv'],
	['quoted path', ({ write }) => write("state/a 'quoted' file.csv"), "state/a 'quoted' file.csv"]
]) {
	test(`CSV CLI rejects ${name} state CSV`, () => repository((repo) => {
		change(repo);
		const result = repo.cli(repo.base, repo.commit());
		rejected(result, /rejected added or changed CSV files/);
		assert.ok(result.stderr.includes(JSON.stringify(path)), result.stderr);
	}));
}

for (const [name, change] of [
	['deleted', ({ git }) => git('rm', '--quiet', 'state/legacy.csv')],
	['renamed out', ({ git }) => git('mv', 'state/legacy.csv', 'removed.csv')],
	['outside state', ({ write }) => write('outside.csv', 'changed\n')],
	['unchanged legacy CSV', ({ write }) => write('seed', 'changed\n')],
	['uppercase directory', ({ git }) => {
		git('mv', 'state', 'renamed-state');
		git('mv', 'renamed-state', 'State');
	}],
	['uppercase suffix and other prefixes', ({ write }) => {
		write('state/new.CSV');
		write('other/state/new.csv');
		write('stateful/new.csv');
	}]
]) {
	test(`CSV CLI permits ${name}`, () => repository((repo) => {
		change(repo);
		accepted(repo.cli(repo.base, repo.commit()));
	}));
}

test('CSV CLI compares from the merge base, not the current base tip', () => repository((repo) => {
	repo.git('checkout', '--quiet', '-b', 'candidate');
	repo.write('state/candidate.csv');
	const head = repo.commit();
	repo.git('checkout', '--quiet', '-b', 'base-side', repo.base);
	repo.write('state/base-only.csv');
	const baseTip = repo.commit();
	const result = repo.cli(baseTip, head);
	rejected(result, /state\/candidate\.csv/);
	assert.doesNotMatch(result.stderr, /base-only/);
	accepted(repo.cli(head, repo.base));
}));

test('CSV CLI ignores CSV edits made only on the base side after divergence', () => repository((repo) => {
	repo.git('checkout', '--quiet', '-b', 'candidate');
	repo.write('seed', 'candidate\n');
	const head = repo.commit();
	repo.git('checkout', '--quiet', '-b', 'base-side', repo.base);
	repo.write('state/legacy.csv', 'base-side\n');
	accepted(repo.cli(repo.commit(), head));
}));

for (const [name, range, message] of [
	['invalid base', ({ base }) => ['missing-base', base], /cannot resolve BASE/],
	['invalid head', ({ base }) => [base, 'missing-head'], /cannot resolve HEAD/],
	['missing head', ({ base }) => [base, ''], /requires both BASE and HEAD/],
	['missing base on pull request', ({ base }) => ['', base], /requires both BASE and HEAD/],
	['zero head', ({ base }) => [base, '0'.repeat(40)], /cannot resolve HEAD/],
	['option-shaped base', ({ base }) => ['--help', base], /cannot resolve BASE/],
	['dispatch invalid head', () => ['', 'missing-head', 'workflow_dispatch'], /cannot resolve HEAD/],
	['push zero base invalid head', () => ['0'.repeat(40), 'missing-head', 'push'], /cannot resolve HEAD/],
	['push zero base missing head', () => ['0'.repeat(40), '', 'push'], /requires HEAD/],
	['zero base on pull request', ({ base }) => ['0'.repeat(40), base], /cannot resolve BASE/]
]) {
	test(`CSV CLI fails closed for ${name}`, () => repository((repo) => {
		rejected(repo.cli(...range(repo)), message);
	}));
}

test('CSV CLI fails closed for commits with no common ancestor', () => repository((repo) => {
	repo.git('checkout', '--quiet', '--orphan', 'unrelated');
	repo.git('rm', '--quiet', '-rf', '.');
	repo.write('new-root');
	rejected(repo.cli(repo.base, repo.commit()), /cannot find a merge base/);
}));

for (const [name, range] of [
	['no supplied range', () => ['', '', '']],
	['manual dispatch with current head', ({ base }) => ['', base, 'workflow_dispatch']],
	['branch creation', ({ base }) => ['0'.repeat(40), base, 'push']]
]) {
	test(`CSV CLI reports no integrity certification for ${name}`, () => repository((repo) => {
		const result = repo.cli(...range(repo));
		accepted(result, /not run: no commit range was supplied\. No whole-tree integrity certification/);
		assert.doesNotMatch(result.stdout, /passed/);
	}));
}
